<?php

namespace App\Services\Digital;

class ProviderRejection extends \RuntimeException
{
    public function __construct(public readonly int $status)
    {
        parent::__construct(match ($status) {
            401 => 'رفضت الشركة المصادقة بمفتاح API المحفوظ؛ راجع المفتاح وتفعيله لدى المزود.',
            403 => 'رفضت الشركة صلاحية الوصول؛ اطلب من المزود مراجعة صلاحيات الحساب والخدمة وعنوان الاتصال المعتمد.',
            404 => 'مسار الخدمة غير متاح لدى الشركة؛ راجع عنوان الربط وإصدار API مع المزود.',
            408, 504 => 'انتهت مهلة استجابة الشركة؛ أعد الاستعلام لاحقًا.',
            429 => 'وصلت إلى حد الاستعلامات لدى الشركة؛ انتظر قليلًا ثم أعد الاستعلام.',
            400, 422 => 'رفضت الشركة بيانات الاستعلام؛ راجع تفاصيل ربط الخدمة والفئة المطلوبة.',
            default => $status >= 500 ? 'خادم الشركة غير متاح حاليًا؛ أعد الاستعلام لاحقًا.' : 'لم يقبل خادم الشركة الطلب؛ راجع حالة الحساب والخدمة لدى المزود.',
        });
    }
}
